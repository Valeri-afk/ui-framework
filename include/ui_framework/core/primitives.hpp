#pragma once

#include "SDL3/SDL.h"

/**
 * @namespace primitives
 * @brief Набор функций для рисования графических примитивов в SDL3
 *
 * Все функции используют формат RGBA (каждый канал 0-255) и поддерживают
 * прозрачность через альфа-канал.
 * Координаты принимаются в формате float для удобства работы с UI и анимациями.
 */
namespace primitives
{

    /**
     * @brief Рисует контур прямоугольника
     *
     * @param renderer  Рендерер SDL
     * @param x1        X-координата левого верхнего угла
     * @param y1        Y-координата левого верхнего угла
     * @param x2        X-координата правого нижнего угла
     * @param y2        Y-координата правого нижнего угла
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисован
     * @return false    Ошибка рисования
     *
     * @note Если x1 == x2 или y1 == y2, рисуется линия или точка
     * @note Толщина линии всегда 1 пиксель
     * @note Координаты округляются до ближайшего целого
     */
    bool rectangleRGBA(SDL_Renderer *renderer, float x1, float y1, float x2, float y2,
                       Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует контур прямоугольника со скруглёнными углами
     *
     * @param renderer  Рендерер SDL
     * @param x1        X-координата левого верхнего угла
     * @param y1        Y-координата левого верхнего угла
     * @param x2        X-координата правого нижнего угла
     * @param y2        Y-координата правого нижнего угла
     * @param rad       Радиус скругления углов в пикселях (float)
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисован
     * @return false    Ошибка рисования (неверный радиус или рендерер)
     *
     * @note Если rad <= 1, рисуется обычный прямоугольник без скругления
     * @note Радиус автоматически уменьшается, если превышает половину ширины/высоты
     * @note Координаты и радиус округляются до ближайшего целого
     */
    bool roundedRectangleRGBA(SDL_Renderer *renderer, float x1, float y1, float x2, float y2,
                              float rad, Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует залитый прямоугольник (сплошная заливка)
     *
     * @param renderer  Рендерер SDL
     * @param x1        X-координата левого верхнего угла
     * @param y1        Y-координата левого верхнего угла
     * @param x2        X-координата правого нижнего угла
     * @param y2        Y-координата правого нижнего угла
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисован
     * @return false    Ошибка рисования
     *
     * @note Если x1 == x2 или y1 == y2, рисуется линия или точка
     * @note Для полупрозрачной заливки используйте a < 255
     * @note Координаты округляются до ближайшего целого
     */
    bool boxRGBA(SDL_Renderer *renderer, float x1, float y1, float x2, float y2,
                 Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует залитый прямоугольник со скруглёнными углами
     *
     * @param renderer  Рендерер SDL
     * @param x1        X-координата левого верхнего угла
     * @param y1        Y-координата левого верхнего угла
     * @param x2        X-координата правого нижнего угла
     * @param y2        Y-координата правого нижнего угла
     * @param rad       Радиус скругления углов в пикселях (float)
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисован
     * @return false    Ошибка рисования (неверный радиус или рендерер)
     *
     * @note Если rad <= 1, рисуется обычный залитый прямоугольник
     * @note Радиус автоматически уменьшается, если превышает половину ширины/высоты
     * @note Для полупрозрачной заливки используйте a < 255
     * @note Координаты и радиус округляются до ближайшего целого
     */
    bool roundedBoxRGBA(SDL_Renderer *renderer, float x1, float y1, float x2, float y2,
                        float rad, Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует линию (отрезок) между двумя точками
     *
     * @param renderer  Рендерер SDL
     * @param x1        X-координата начальной точки
     * @param y1        Y-координата начальной точки
     * @param x2        X-координата конечной точки
     * @param y2        Y-координата конечной точки
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисована
     * @return false    Ошибка рисования
     *
     * @note Толщина линии всегда 1 пиксель
     * @note Координаты округляются до ближайшего целого
     */
    bool lineRGBA(SDL_Renderer *renderer, float x1, float y1, float x2, float y2,
                  Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует вертикальную линию
     *
     * @param renderer  Рендерер SDL
     * @param x         X-координата линии
     * @param y1        Y-координата начальной точки
     * @param y2        Y-координата конечной точки
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисована
     * @return false    Ошибка рисования
     *
     * @note Толщина линии всегда 1 пиксель
     * @note Если y1 == y2, рисуется точка
     * @note Координаты округляются до ближайшего целого
     */
    bool vlineRGBA(SDL_Renderer *renderer, float x, float y1, float y2,
                   Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует горизонтальную линию
     *
     * @param renderer  Рендерер SDL
     * @param x1        X-координата начальной точки
     * @param x2        X-координата конечной точки
     * @param y         Y-координата линии
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисована
     * @return false    Ошибка рисования
     *
     * @note Толщина линии всегда 1 пиксель
     * @note Если x1 == x2, рисуется точка
     * @note Координаты округляются до ближайшего целого
     */
    bool hlineRGBA(SDL_Renderer *renderer, float x1, float x2, float y,
                   Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует один пиксель
     *
     * @param renderer  Рендерер SDL
     * @param x         X-координата пикселя
     * @param y         Y-координата пикселя
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисован
     * @return false    Ошибка рисования
     *
     * @note Координаты округляются до ближайшего целого
     */
    bool pixelRGBA(SDL_Renderer *renderer, float x, float y,
                   Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует дугу окружности
     *
     * @param renderer  Рендерер SDL
     * @param x         X-координата центра окружности
     * @param y         Y-координата центра окружности
     * @param rad       Радиус окружности в пикселях (float)
     * @param start     Начальный угол в градусах (0 = вправо, 90 = вниз)
     * @param end       Конечный угол в градусах
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисована
     * @return false    Ошибка рисования (неверный радиус)
     *
     * @note Если rad == 0, рисуется точка
     * @note Углы автоматически нормализуются в диапазон 0-359°
     * @note Толщина линии всегда 1 пиксель
     * @note Дуга рисуется по часовой стрелке
     * @note Координаты и радиус округляются до ближайшего целого
     */
    bool arcRGBA(SDL_Renderer *renderer, float x, float y, float rad,
                 Sint16 start, Sint16 end,
                 Uint8 r, Uint8 g, Uint8 b, Uint8 a);

    /**
     * @brief Рисует залитый круг
     *
     * @param renderer  Рендерер SDL
     * @param x         X-координата центра круга
     * @param y         Y-координата центра круга
     * @param rad       Радиус круга в пикселях (float)
     * @param r         Красный канал (0-255)
     * @param g         Зелёный канал (0-255)
     * @param b         Синий канал (0-255)
     * @param a         Альфа-канал (0-255), 255 = непрозрачный
     * @return true     Успешно нарисован
     * @return false    Ошибка рисования (неверный радиус)
     *
     * @note Если rad == 0, рисуется точка
     * @note Для полупрозрачной заливки используйте a < 255
     * @note Использует алгоритм Брезенхэма для эффективной отрисовки
     * @note Координаты и радиус округляются до ближайшего целого
     */
    bool filledCircleRGBA(SDL_Renderer *renderer, float x, float y, float rad,
                          Uint8 r, Uint8 g, Uint8 b, Uint8 a);

} // namespace primitives